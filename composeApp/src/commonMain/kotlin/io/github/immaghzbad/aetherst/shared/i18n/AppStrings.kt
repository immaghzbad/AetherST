val LocalAppStrings = compositionLocalOf<AppStrings> { StringsEn }

@Composable
fun rememberAppStrings(): AppStrings {
    return LocalAppStrings.current
}

fun getAppStrings(language: String): AppStrings {
    return when (language.lowercase()) {
        "fa" -> StringsFa
        else -> StringsEn
    }
}

fun getEffectiveStrings(appLanguage: String): AppStrings {
    val lang = if (appLanguage == "auto") {
        try {
            val sys = java.util.Locale.getDefault().language.lowercase()
            if (sys.startsWith("fa")) "fa" else "en"
        } catch (_: Exception) { "en" }
    } else appLanguage
    return getAppStrings(lang)
}
